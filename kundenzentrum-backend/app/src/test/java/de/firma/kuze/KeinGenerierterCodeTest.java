package de.firma.kuze;

import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;

/** Regel 6: Generierter Code entsteht bei jedem Build unter build/ und liegt nie unter src/. */
class KeinGenerierterCodeTest {

    @Test
    void unterSrcLiegtKeinGenerierterCode() throws IOException {
        Path wurzel = Path.of(System.getProperty("projekt.verzeichnis"));
        List<Path> generiert;
        try (Stream<Path> dateien = Files.walk(wurzel)) {
            generiert = dateien
                    .filter(p -> wurzel.relativize(p).toString().matches("[^/]+/src/.*\\.java"))
                    .filter(KeinGenerierterCodeTest::istGeneriert)
                    .toList();
        }
        assertThat(generiert).as("generierte Dateien unter src/").isEmpty();
    }

    private static boolean istGeneriert(Path datei) {
        try {
            String inhalt = Files.readString(datei);
            // zusammengesetzt, damit dieser Test sich nicht selbst findet
            return inhalt.contains("auto generated by " + "OpenAPI Generator")
                    || inhalt.contains("@jakarta.annotation." + "Generated")
                    || inhalt.matches("(?s)^package de\\.firma\\.kuze\\.sap\\.[a-z]+\\.client\\b.*");
        } catch (IOException e) {
            throw new java.io.UncheckedIOException(e);
        }
    }
}
